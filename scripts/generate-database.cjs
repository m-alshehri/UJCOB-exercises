const fs = require("fs"),
  vm = require("vm");
const context = { window: {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync("question-banks.js", "utf8"), context);
const courses = context.window.COURSES;
const quote = (v) => "'" + String(v).replaceAll("'", "''") + "'";
let sql = `-- Generated by scripts/generate-database.cjs. Preserves question IDs and history.
create temporary table tamareen_seed(code text,topic text,question text,correct_answer text,wrong_answers jsonb,explanation text);
insert into tamareen_seed values
`;
const seedRows=[];
for(const [code,course] of Object.entries(courses))for(const q of course.questions)seedRows.push('('+[code,q.topic||'General',q.q,q.c,JSON.stringify(q.w),q.e].map(quote).join(',')+')');
sql+=seedRows.join(',\n')+`;

insert into public.topics(course_id,name)
select distinct c.id,s.topic from tamareen_seed s join public.courses c on c.code=s.code on conflict(course_id,name) do nothing;
insert into public.questions(course_id,topic_id,question,correct_answer,wrong_answers,explanation)
select c.id,t.id,s.question,s.correct_answer,s.wrong_answers,s.explanation from tamareen_seed s
join public.courses c on c.code=s.code join public.topics t on t.course_id=c.id and t.name=s.topic
where not exists(select 1 from public.questions q where q.course_id=c.id and q.question=s.question);
update public.questions q set topic_id=t.id from tamareen_seed s join public.courses c on c.code=s.code
join public.topics t on t.course_id=c.id and t.name=s.topic where q.course_id=c.id and q.question=s.question and q.topic_id is null;
drop table pg_temp.tamareen_seed;
`;
fs.writeFileSync("supabase/seed_questions.sql", sql);
const c = {};
c.window = c;
vm.createContext(c);
vm.runInContext(fs.readFileSync("js/lab-content.js", "utf8"), c);
vm.runInContext(fs.readFileSync("js/catalog.js", "utf8"), c);
let lab = `-- Stable lab identifiers. Preserve old rows; UI also recognizes legacy keys.\ncreate table if not exists public.lab_exercises(lab_type text not null,exercise_key text not null,course_code text not null,title text not null,legacy_index integer not null,primary key(lab_type,exercise_key));\nalter table public.lab_exercises enable row level security;\ndrop policy if exists "Public lab catalogue" on public.lab_exercises;\ncreate policy "Public lab catalogue" on public.lab_exercises for select using(true);\n`;
for (const [type, value] of Object.entries(c.window.LAB_CATALOG))
  for (const e of value.exercises)
    lab += `insert into public.lab_exercises values(${quote(type)},${quote(e.id)},${quote(value.code)},${quote(e.title)},${e.legacyIndex}) on conflict(lab_type,exercise_key) do update set title=excluded.title;\n`;
lab += `update public.lab_progress p set exercise_key=e.exercise_key from public.lab_exercises e where p.lab_type=e.lab_type and p.exercise_key=e.legacy_index::text and not exists(select 1 from public.lab_progress other where other.user_id=p.user_id and other.course_id=p.course_id and other.lab_type=p.lab_type and other.exercise_key=e.exercise_key);\n`;
lab += `create or replace function public.validate_lab_exercise() returns trigger language plpgsql set search_path=public,pg_temp as $$ begin if not exists(select 1 from public.lab_exercises e join public.courses c on c.code=e.course_code where e.lab_type=new.lab_type and e.exercise_key=new.exercise_key and c.id=new.course_id) then raise exception 'Unknown lab exercise';end if;return new;end $$;\ndrop trigger if exists lab_exercise_valid on public.lab_progress;\ncreate trigger lab_exercise_valid before insert or update on public.lab_progress for each row execute function public.validate_lab_exercise();\n`;
fs.writeFileSync("supabase/migrations/003_lab_catalog.sql", lab);
const base = fs.readFileSync("supabase/migrations/001_base.sql", "utf8");
const migrations = [
  "001_base.sql",
  "002_reliable_practice.sql",
  "003_lab_catalog.sql",
]
  .map((f) => fs.readFileSync("supabase/migrations/" + f, "utf8"))
  .join("\n");
fs.writeFileSync("supabase/schema.sql", "begin;\n"+migrations+"\nnotify pgrst, 'reload schema';\ncommit;\n");
fs.writeFileSync(
  "supabase/setup.sql",
  "-- Canonical setup or upgrade. Execute as one transaction.\nbegin;\n" +
    migrations +
    "\n" +
    sql +
    "\nnotify pgrst, 'reload schema';\ncommit;\n",
);
